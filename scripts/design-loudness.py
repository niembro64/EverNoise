"""Offline calibration for the unchanged build-23 filters; no runtime SciPy.

K weighting: ITU-R BS.1770-5 Annex 1, Tables 1/2 (48 kHz).
This is stationary-noise calibration, not a gated programme-loudness meter.
"""
from pathlib import Path
import argparse
import json
import numpy as np
from scipy import signal

ROOT = Path(__file__).resolve().parents[1]
K_SOS = np.array([
    [1.53512485958697, -2.69169618940638, 1.19839281085285,
     1, -1.69065929318241, .73248077421585],
    [1, -2, 1, 1, -1.99004745483398, .99007225036621],
])


def design():
    bank = json.loads((ROOT / "Store/complementary-design-v1.json").read_text())
    impulse = np.zeros(192000); impulse[0] = 1
    powers = []
    for split in bank["crossoverSOS"]:
        h = signal.sosfilt(np.vstack([bank["commonSOS"], split, K_SOS]), impulse)
        # Midpoint uniform excitation has variance (1 - 2^-48) / 3.
        powers.append(float(np.dot(h, h) * bank["commonGain"]**2 * (1-2**-48)/3))
    # 4x, 129-tap windowed-sinc reconstruction; group delay 16 source samples.
    fir = signal.firwin(129, .25, window=("kaiser", 8.6)) * 4
    phases = [np.pad(fir[p::4], (0, 33-len(fir[p::4]))) for p in range(4)]
    def row(v): return "{" + ", ".join(format(float(x), ".17g") for x in v) + "}"
    header = """// Generated by scripts/design-loudness.py --write. Do not hand-edit.
#ifndef BN_LOUDNESS_COEFFICIENTS_H
#define BN_LOUDNESS_COEFFICIENTS_H
#include "BNComplementaryCoefficients.h"
"""
    header += "static const BNSecondOrderCoefficients BNKWeighting[2] = {\n"
    header += ",\n".join("    " + row([*s[:3], *s[4:]]) for s in K_SOS) + "\n};\n"
    header += "static const double BNBandKPower[3] = " + row(powers) + ";\n"
    header += "static const double BNTruePeakFIR[4][33] = {\n"
    header += ",\n".join("    " + row(p) for p in phases) + "\n};\n#endif\n"
    record = {"sampleRate": 48000, "baseTargetLUFS": -20, "offsetDB": [-18, 3],
              "bandKPower": powers, "kWeightingSOS": K_SOS.tolist(),
              "detectorOversampling": 4, "detectorTaps": 129,
              "detectorDelayFrames": 16, "limiterSampleCeilingDBFS": -3,
              "postConversionAcceptanceDBTP": -2,
              "meterTimeConstantSeconds": 30, "correctionTimeConstantSeconds": 60,
              "maximumCorrectionDB": 1}
    return header, record


if __name__ == "__main__":
    parser = argparse.ArgumentParser(); parser.add_argument("--write", action="store_true")
    args = parser.parse_args(); header, record = design()
    path = ROOT / "Sources/BrownNoiseDSP/BNLoudnessCoefficients.h"
    if args.write:
        path.write_text(header)
        (ROOT / "Store/loudness-design-v1.json").write_text(json.dumps(record, indent=2)+"\n")
    else:
        assert path.read_text() == header
    print(json.dumps(record, indent=2))
