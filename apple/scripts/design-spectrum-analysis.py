#!/usr/bin/env python3
"""Design/verify the analysis-only FIR; never changes the audio generator."""
import argparse
import json
from pathlib import Path
import numpy as np
from scipy.signal import firwin, freqz

root = Path(__file__).resolve().parents[1]
h = firwin(257, 1000, fs=48000, window=("kaiser", 12)).astype(np.float32)
f = np.r_[np.linspace(0, 100, 1001), np.linspace(3000, 24000, 100001)]
_, response = freqz(h.astype(float), worN=f, fs=48000)
pass_error = float(np.max(abs(20*np.log10(abs(response[:1001])))))
stop = float(20*np.log10(abs(response[1001:]).max()))
assert pass_error < .0001 and stop < -120
header = "// Generated by scripts/design-spectrum-analysis.py --write. Analysis only.\n"
header += "#ifndef BN_SPECTRUM_DECIMATION_H\n#define BN_SPECTRUM_DECIMATION_H\n"
header += "static const float BNSpectrumDecimationFIR[257] = {\n"
header += ",\n".join("    " + ", ".join(f"{float(v):.12e}f" for v in h[i:i+4]) for i in range(0,len(h),4))
header += "\n};\n#endif\n"
p = root / "Sources/SpectrumAnalysis/BNSpectrumDecimation.h"
parser = argparse.ArgumentParser(); parser.add_argument("--write", action="store_true")
if parser.parse_args().write:
    p.write_text(header)
else:
    assert p.read_text() == header
print(json.dumps(dict(taps=len(h), delayFrames=128, rate=48000, decimation=8,
                     passbandErrorDB_0to100Hz=pass_error, stopbandMaximumDB_3to24kHz=stop)))
