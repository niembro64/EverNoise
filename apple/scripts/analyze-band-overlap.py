"""Measure the existing production bands after Apple's actual conversion/mix.

Input: 65-second stereo renders low/mid/high/equal/default.wav, generated by
Scripts/render-stereo.swift linked to the unchanged production DSP source.
No filter design or audio-file editing is performed by this analysis.
"""
import hashlib
import json
import sys
import warnings
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy import signal
from scipy.io import wavfile

root = Path(sys.argv[1])
curves, waveforms, records = {}, {}, {}
centers = np.geomspace(20, 20000, 600)

def smooth(f, p, at=centers):
    return np.array([np.mean(p[(f >= c * 2**(-1/24)) & (f <= c * 2**(1/24))]) for c in at])

for name in ["low", "mid", "high", "equal", "default"]:
    path = root / (name + ".wav")
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", wavfile.WavFileWarning)
        rate, x = wavfile.read(path)
    assert rate == 48000 and x.ndim == 2 and x.shape[1] == 2
    assert np.isfinite(x).all() and np.max(np.abs(x)) < 1
    x = x[rate:].astype(np.float64)  # Exclude startup fade; 64 s per channel.
    f, psd = signal.welch(x, rate, nperseg=96000, noverlap=48000, axis=0, detrend=False)
    psd = psd.mean(axis=1)
    curves[name] = psd
    waveforms[name] = x
    records[name] = {"wavSHA256": hashlib.sha256(path.read_bytes()).hexdigest(),
                     "sampleRate": rate, "analyzedSecondsPerChannel": len(x)/rate,
                     "rms": float(np.sqrt(np.mean(x*x))), "peak": float(np.max(np.abs(x)))}

power_sum = sum(curves[name] for name in ["low", "mid", "high"])
sample_sum = sum(waveforms[name] for name in ["low", "mid", "high"])
sample_error = float(np.max(np.abs(sample_sum - waveforms["equal"])))
assert sample_error < 2e-7, sample_error
smoothed = {name: smooth(f, p) for name, p in curves.items()}
expected = smooth(f, power_sum)
power_error_db = 10*np.log10(smoothed["equal"] / expected)
assert np.percentile(np.abs(power_error_db), 95) < 0.4
reference = float(smooth(f, power_sum, np.array([125]))[0])
db = lambda p: 10*np.log10(np.maximum(p, 1e-30)/reference)
sample_frequencies = np.array([40, 80, 125, 250, 500, 1000, 2000, 3000, 4000, 6000, 8000, 12000, 16000])
samples = {name: dict(zip(map(str, sample_frequencies), db(smooth(f, p, sample_frequencies)).tolist()))
           for name, p in curves.items()}

# True pair intersections of measured density, not nominal filter pole labels.
crossovers = []
for first, second, lo, hi in [("low", "mid", 150, 2500), ("mid", "high", 1000, 12000)]:
    mask = (centers >= lo) & (centers <= hi)
    band = np.flatnonzero(mask)
    i = band[np.argmin(np.abs(np.log(smoothed[first][mask]/smoothed[second][mask])))]
    crossovers.append({"pair": [first, second], "approximateHz": float(centers[i]),
                       "sumRelativeTo125Hz_dB": float(db(smoothed["equal"][i]))})

fig, axes = plt.subplots(2, 1, figsize=(10, 8.2), constrained_layout=True)
colors = {"low": "#ad6c66", "mid": "#5f8e60", "high": "#677fb4"}
for name in ["low", "mid", "high"]:
    axes[0].semilogx(centers, db(smoothed[name]), color=colors[name], lw=1.5, label=name.title())
axes[0].semilogx(centers, db(smoothed["equal"]), color="#242c38", lw=2.4, label="All three at equal settings")
axes[0].axhline(0, color="#999999", ls=":", lw=1, label="Flat-power reference")
axes[0].set(title="Current bands overlap, but do not sum to flat power", ylim=(-65, 15))
axes[1].semilogx(centers, db(smoothed["equal"]), color="#949aa3", lw=1.5, label="Equal settings")
axes[1].semilogx(centers, db(smoothed["default"]), color="#4a536f", lw=2.4,
                 label="New default: buttons 3 / 3 / 2 (Off counts as button 1)")
axes[1].set(title="The requested default keeps the existing filters and lowers the high layer", ylim=(-65, 15))
for ax in axes:
    ax.set(xlim=(20, 20000), xlabel="Frequency (Hz)", ylabel="Power density (dB relative to equal mix at 125 Hz)")
    ax.set_xticks([20, 50, 100, 250, 500, 1000, 2000, 5000, 10000, 20000],
                  ["20", "50", "100", "250", "500", "1k", "2k", "5k", "10k", "20k"])
    ax.grid(alpha=.20); ax.legend(loc="upper right", fontsize=8)
fig.savefig("Store/band-overlap-v22.png", dpi=170)
record = {"method": "Production paired DSP + AVAudioEngine offline SRC/mix at 48 kHz; 64 steady-state seconds/channel; stereo-averaged Welch PSD with 2 s Hann windows/50% overlap and 1/12-octave display smoothing.",
          "reference": "Equal mix density at 125 Hz; one common reference for every curve. This is source electrical power density, not acoustic SPL or equal loudness.",
          "renders": records, "sampleSumMaximumError": sample_error,
          "measuredMixVsPowerSum95thPercentileError_dB": float(np.percentile(np.abs(power_error_db), 95)),
          "approximateEqualSettingCrossovers": crossovers, "relativePowerDensityByHz_dB": samples,
          "defaultButtonsCountingOff": [3,3,2], "defaultInternalLevels": [2,2,1],
          "audioFiltersChanged": False, "perfectPowerComplementaryCrossover": False}
Path("Store/band-overlap-v22.json").write_text(json.dumps(record, indent=2)+"\n")
print(json.dumps({"crossovers": crossovers, "equal_dB": samples["equal"],
                  "default_dB": samples["default"], "sample_error": sample_error,
                  "PSD_sum_error95_dB": record["measuredMixVsPowerSum95thPercentileError_dB"]}, indent=2))
